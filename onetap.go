// OneTapOptions configures Google's first-party browser credential prompt.
type OneTapOptions struct {
	ClientID      string
	DisableSignUp bool
}

func googleDomainAllowed(want string, p OAuthProfile) bool {
	if want == "" {
		return true
	}
	claims, _ := p.Data.(map[string]any)
	domain, _ := claims["hd"].(string)
	return domain != "" && (want == "*" || domain == want)
}

const oneTapProofPurpose = "google-one-tap/browser"

type oneTapProof struct {
	Nonce            string
	Expires          int64
	Audience, Origin string
}

func (a *Auth) oneTapCookie(value string, age int) *http.Cookie {
	n := a.prefixedCookieName("one_tap")
	if strings.HasPrefix(n, "__Secure-") {
		n = "__Host-" + strings.TrimPrefix(n, "__Secure-")
	}
	return &http.Cookie{Name: n, Value: value, Secure: strings.HasPrefix(a.opts.BaseURL, "https://"), HttpOnly: true, SameSite: http.SameSiteStrictMode, Path: "/", MaxAge: age}
}

// BindOneTapNonce records a five-minute browser challenge generated by host
// server code. Pass a fresh, cryptographically random nonce generated for this
// browser, the configured Google audience and the trusted page origin.
// Expose the nonce through the page or a host session, never as user input.
func (a *Auth) BindOneTapNonce(w http.ResponseWriter, origin, audience, nonce string) error {
	return a.bindOneTapNonce(w.Header(), origin, audience, nonce)
}
func (a *Auth) bindOneTapNonce(headers http.Header, origin, audience, nonce string) error {
	u, err := url.Parse(origin)
	if err != nil || u.User != nil || u.Path != "" || u.RawQuery != "" || u.ForceQuery || u.Fragment != "" || !a.trustedURL(origin, false) || audience == "" || len(nonce) < 16 || len(nonce) > 256 || strings.ContainsAny(nonce, " \r\n\t") {
		return errors.New("authn: invalid One Tap origin, audience or host nonce")
	}
	proof := oneTapProof{Nonce: nonce, Audience: audience, Origin: origin, Expires: a.now().Add(5 * time.Minute).Unix()}
	raw, err := json.Marshal(proof)
	if err != nil {
		return err
	}
	sealed, err := a.sealRecord(oneTapProofPurpose, raw)
	if err != nil {
		return err
	}
	headers.Add("Set-Cookie", a.oneTapCookie(sealed, 300).String())
	return nil
}

// NewOneTap constructs the server plugin. The Google provider configured on the
// auth instance supplies the verifier unless the plugin has a distinct client ID.
func NewOneTap(o OneTapOptions, fallback OAuthProvider) Plugin {
	provider := func(c EndpointContext) (OAuthProvider, error) {
		p := c.Auth.opts.SocialProviders["google"]
		if o.ClientID != "" && p.Config.ClientID != o.ClientID {
			p = fallback
		}
		if p.Config.ClientID == "" || p.VerifyIDToken == nil || o.ClientID != "" && p.Config.ClientID != o.ClientID {
			return p, &APIError{400, "GOOGLE_CLIENT_ID_REQUIRED", "Google One Tap requires a configured client ID and verifier"}
		}
		return p, nil
	}
	origin := func(c EndpointContext) (string, error) {
		v := c.Request.Header.Get("Origin")
		if v == "" || !c.Auth.trustedURL(v, false) {
			return "", &APIError{403, "INVALID_ORIGIN", "A trusted browser origin is required"}
		}
		return v, nil
	}
	invalid := func() error {
		return &APIError{400, "INVALID_TOKEN", "Invalid Google credential or expired browser challenge"}
	}
	return Plugin{ID: "one-tap", ValidateStore: func(s Store) error {
		if _, ok := s.(OAuthStore); !ok {
			return errors.New("authn: One Tap requires an OAuth identity store")
		}
		return nil
	}, Endpoints: []Endpoint{
		{Method: "POST", Path: "/one-tap/nonce", RateLimit: &RateLimitRule{Window: time.Minute, Max: 20}, Handler: func(c EndpointContext) (any, error) {
			from, err := origin(c)
			if err != nil {
				return nil, err
			}
			p, err := provider(c)
			if err != nil {
				return nil, err
			}
			nonce := randomID()
			if err := c.Auth.bindOneTapNonce(c.ResponseHeader, from, p.Config.ClientID, nonce); err != nil {
				return nil, err
			}
			return map[string]string{"nonce": nonce, "clientId": p.Config.ClientID}, nil
		}},
		{Method: "POST", Path: "/one-tap/callback", RateLimit: &RateLimitRule{Window: time.Minute, Max: 20}, Handler: func(c EndpointContext) (any, error) {
			from, err := origin(c)
			if err != nil {
				return nil, err
			}
			p, err := provider(c)
			if err != nil {
				return nil, err
			}
			raw, _ := c.Body["idToken"].(string)
			if raw == "" || len(raw) > 64<<10 {
				return nil, invalid()
			}
			bound, err := c.Request.Cookie(c.Auth.oneTapCookie("", 0).Name)
			if err != nil {
				return nil, invalid()
			}
			plain, err := c.Auth.openRecord(oneTapProofPurpose, bound.Value)
			var challenge oneTapProof
			if err != nil || json.Unmarshal(plain, &challenge) != nil || challenge.Nonce == "" || challenge.Audience != p.Config.ClientID || challenge.Origin != from || !time.Unix(challenge.Expires, 0).After(c.Auth.now()) {
				return nil, invalid()
			}
			ctx := c.Request.Context()
			if p.HTTPClient != nil {
				ctx = context.WithValue(ctx, oauth2.HTTPClient, p.HTTPClient)
			}
			ctx, cancel := context.WithTimeout(ctx, 30*time.Second)
			defer cancel()
			profile, exp, err := p.VerifyIDToken(ctx, raw, challenge.Nonce)
			if err != nil || !validSocialProfile(profile) || !exp.After(c.Auth.now()) {
				return nil, invalid()
			}
			account, _, err := c.Auth.completeProfile(ctx, c.Request, "google", profile, OAuthTokens{IDToken: raw, Scope: "openid,profile,email"}, OAuthLoginOptions{OneTapNonce: challenge.Nonce, OneTapExpires: time.Unix(challenge.Expires, 0), IDTokenValidUntil: exp, DisableSignUp: o.DisableSignUp, AllowVerifiedEmailLink: p.AllowVerifiedEmailLink})
			if errors.Is(err, ErrIDTokenUsed) {
				return nil, invalid()
			}
			if errors.Is(err, ErrOAuthLinkRequired) {
				return nil, &APIError{401, "ACCOUNT_NOT_LINKED", "Account not linked"}
			}
			if err != nil {
				return nil, err
			}
			c.ResponseHeader.Add("Set-Cookie", c.Auth.oneTapCookie("", -1).String())
			if err := c.Auth.addSessionCookieHeaders(c.ResponseHeader, c.Request, account.Token, true); err != nil {
				return nil, err
			}
			return map[string]any{"token": account.Token, "user": account.User}, nil
		}},
	}}
}
